extension TranslationExtension on BuildContext {
  String tr(String key) {
    final locale = Localizations.localeOf(this).languageCode;
    final lang = AppLanguage.fromCode(locale);
    return AppTranslations.get(key, lang);
  }

  String trFinanceCategory(String category) {
    final key = 'finance_cat_${category.toLowerCase()}';
    final translated = tr(key);
    return translated != key ? translated : category.replaceAll('_', ' ').toUpperCase();
  }

  String trMovementType(String type) {
    final key = 'movement_${type.toLowerCase()}';
    final translated = tr(key);
    return translated != key ? translated : type.toUpperCase();
  }

  String trSpecies(String species) {
    final key = 'species_${species.toLowerCase()}';
    final translated = tr(key);
    return translated != key ? translated : species;
  }

  String trPurpose(String purpose) {
    final key = 'purpose_${purpose.toLowerCase()}';
    final translated = tr(key);
    return translated != key ? translated : purpose.toUpperCase();
  }

  String trTaskCategory(String cat) {
    final key = 'tasks_cat_${cat.toLowerCase()}';
    final translated = tr(key);
    return translated != key ? translated : cat.toUpperCase();
  }

  String trRecurrence(String rec) {
    final key = 'tasks_repeat_${rec.toLowerCase()}';
    final translated = tr(key);
    return translated != key ? translated : rec;
  }
